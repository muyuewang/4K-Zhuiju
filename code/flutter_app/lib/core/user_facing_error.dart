/// 「可以直接给用户看」的异常标记。
///
/// ## 为什么需要这个标记
///
/// `friendlyError()` 的职责是把技术异常翻译成人话。但它有个天然的盲区：
/// 有些异常**本身就是人话**——比如插件层抛出的
/// 「橘汁：请求时间戳过期」、取址层的「这条线路需要二次解析」。
/// 这些消息是脚本作者精心写的中文原因，比任何通用文案都有用。
///
/// 之前 `friendlyError` 不认识它们，全部落到兜底分支换成
/// 「出错了，请重试」——把最有价值的那句话丢掉了。
/// 2026-11-19 排查橘汁时，宿主已经把 `code=100001 请求时间戳过期`
/// 透传到异常里，界面上却还是「出错了」，等于白做。
///
/// ## 为什么用接口而不是判断具体类型
///
/// 直接 `if (e is PluginFetchException)` 会让 `core/api.dart` 反向依赖
/// 插件层——而 api.dart 是更底层的 HTTP 客户端，不该知道插件存在。
/// 用一个谁都能实现的空接口，两边都只依赖这个文件，方向是单向的。
///
/// ## 使用约定
///
/// 实现这个接口 = 「我的 message 是给人看的，直接显示」。
/// 所以**不要**把技术细节（堆栈、状态码原文、base64）放进 message；
/// 需要技术细节就另外写日志，日志有完整的上下文。
library;

/// 消息可以直接展示给用户的异常。
abstract interface class UserFacingException implements Exception {
  /// 面向用户的失败原因。必须是一句能读懂、能据此行动的中文。
  String get message;
}